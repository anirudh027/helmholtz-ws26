"""Gather the per-sequence rows that ``track_all.py`` prints into one table.

    python scripts/collect_results.py /mnt/1t/tracks/*.log --out results/tracking

Writes ``all_runs.csv`` (one row per dataset / sequence / method; the latest run wins)
and ``summary.md`` (mean over sequences per dataset and method, best value in bold).
"""

import argparse
import ast
import glob
import os
import re

import pandas as pd

CTC = ["TRA", "DET", "LNK", "BC", "CT"]
PT = ["pt_det_recall", "pt_link_acc", "pt_survival", "pt_div_recall", "pt_div_precision_annot", "pt_id_switches"]
ROW = re.compile(r"^\[[^\]]+\] (\{.*\})\s*$")


def read_rows(paths):
    rows = []
    for p in paths:
        for line in open(p, errors="replace"):
            m = ROW.match(line.strip())
            if m:
                try:
                    d = ast.literal_eval(m.group(1).replace("nan", "None"))
                except (ValueError, SyntaxError):
                    continue
                if d.get("ok"):
                    d["source"] = os.path.basename(p)
                    rows.append(d)
    df = pd.DataFrame(rows)
    if "masks" not in df:
        df["masks"] = df.get("provisional_masks", False).map({True: "cellpose", False: "provided"})
    df["dataset"] = df["dataset"].map(lambda d: os.path.basename(d[4:].rstrip("/")) if str(d).startswith("ctc:") else d)
    return df.drop_duplicates(["dataset", "seq", "method", "masks"], keep="last")


def table(df, cols):
    cols = [c for c in cols if c in df and df[c].notna().any()]
    if not cols:
        return ""
    g = df.groupby(["dataset", "masks", "method"])[cols].mean(numeric_only=True).reset_index()
    g["n_seq"] = df.groupby(["dataset", "masks", "method"]).size().values
    lines = []
    for (ds, mk), sub in g.groupby(["dataset", "masks"]):
        sub = sub.dropna(subset=cols, how="all")
        if sub.empty:
            continue
        lines.append(f"\n### {ds} ({mk} masks, {int(sub['n_seq'].max())} seq)\n")
        lines.append("| method | " + " | ".join(c.replace("pt_", "") for c in cols) + " |")
        lines.append("|---" * (len(cols) + 1) + "|")
        best = {c: (sub[c].min() if c == "pt_id_switches" else sub[c].max()) for c in cols}
        for r in sub.sort_values(cols[0], ascending=False).itertuples():
            cells = []
            for c in cols:
                v = getattr(r, c)
                s = "" if pd.isna(v) else (f"{v:.0f}" if c == "pt_id_switches" else f"{v:.4f}")
                cells.append(f"**{s}**" if s and v == best[c] else s)
            lines.append(f"| {r.method} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("logs", nargs="+")
    ap.add_argument("--out", default="results/tracking")
    args = ap.parse_args()
    paths = sorted({p for pat in args.logs for p in glob.glob(pat)})
    df = read_rows(paths)
    os.makedirs(args.out, exist_ok=True)
    df.to_csv(os.path.join(args.out, "all_runs.csv"), index=False)
    md = ["# Tracking results\n", "Mean over sequences. Generated by `scripts/collect_results.py`.\n",
          "## Full CTC ground truth\n", table(df, CTC), "\n## Point ground truth (annotated cells only)\n",
          table(df, PT)]
    with open(os.path.join(args.out, "summary.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print(f"{len(df)} rows -> {args.out}/all_runs.csv, summary.md")


if __name__ == "__main__":
    main()
